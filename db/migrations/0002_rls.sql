DO $$ BEGIN
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='nazir_app') THEN CREATE ROLE nazir_app NOLOGIN; END IF;
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='nazir_worker') THEN CREATE ROLE nazir_worker NOLOGIN; END IF;
END $$;
GRANT USAGE ON SCHEMA nazir TO nazir_app,nazir_worker;
CREATE FUNCTION nazir.current_workspace_id() RETURNS uuid LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, nazir AS $$
BEGIN
 IF current_setting('role',true)='nazir_app' THEN
  RETURN (SELECT workspace_id FROM nazir.members WHERE id=nullif(current_setting('app.member_id',true),'')::uuid AND status='active');
 ELSIF current_setting('role',true)='nazir_worker' THEN
  RETURN nullif(current_setting('app.workspace_id',true),'')::uuid;
 END IF;
 RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION nazir.current_workspace_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION nazir.current_workspace_id() TO nazir_app,nazir_worker;
