import en from '../../../messages/en.json';
import ar from '../../../messages/ar.json';
import type { PdfSection } from '../reports/pdf';
import type { SafetyDetail } from './read';

/** What the safety report PDF says: the same verdict, scope line and weaknesses as the screen. */
export function safetyPdf(detail: SafetyDetail, lang: 'en' | 'ar', date: string): { title: string; head: string[]; sections: PdfSection[]; footer: string } {
  const t = (lang === 'ar' ? ar : en).safetyScreen;
  const head = [
    detail.verdict ? t.verdict[detail.verdict] : '',
    ...(detail.scope === 'replies_only' ? [t.repliesOnly] : detail.scope === 'sample' ? [t.sampleLine] : []),
    `${detail.agent ?? ''}  ${date}`.trim(),
  ].filter(Boolean);
  const found = detail.weaknesses.filter((w) => w.outcome === 'broken' || w.outcome === 'partial');
  const sections: PdfSection[] = found.map((w) => ({
    title: `${w.severity ? t.severity[w.severity] : ''}: ${w.title[lang]}`,
    lines: [
      ...(w.proven ? [t.proven[w.proven]] : []),
      `${t.tried}: ${w.tried[lang]}`,
      ...(w.reply ? [`${t.replyLabel}: ${w.reply.slice(0, 600)}`] : []),
      ...(w.did ? [`${t.didLabel}: ${w.didTranslations?.[lang] ?? w.did}`] : []),
      `${t.fix}: ${w.fix[lang]}`,
      `${t.mapping}: ${w.mapping.join(', ')}`,
    ],
  }));
  if (!found.length) sections.push({ title: t.weaknesses, lines: [t.noWeakness] });
  const other = detail.weaknesses.filter((w) => w.outcome !== 'broken' && w.outcome !== 'partial');
  if (other.length) sections.push({ title: t.notTested, lines: other.map((w) => `${w.title[lang]}: ${w.reason ? t.reason[w.reason] : t.outcome[w.outcome]}`) });
  if (detail.resisted.length) sections.push({ title: t.outcome.resisted, lines: [t.heldUp.replace('{n}', String(detail.resisted.length))] });
  return { title: `${t.safety}: ${detail.verdict ? t.verdict[detail.verdict] : ''}`, head, sections, footer: lang === 'ar' ? 'محادثات اختبار اصطناعية. أنشئ بواسطة ناظر.' : 'Synthetic test conversations. Generated by Nazir.' };
}
