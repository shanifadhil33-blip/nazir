import { readFile } from 'node:fs/promises';
import { expect, it } from 'vitest';
import { PDFDocument } from 'pdf-lib';
import { extractText, getDocumentProxy } from 'unpdf';
import { assembleReport } from '../../src/server/reports/build';
import { buildReportPdf, clientReportSections, type PdfExtras } from '../../src/server/reports/pdf';
import { cleanPdfText, shapePdfLine, wrapPdfText } from '../../src/server/reports/pdf-text';

const body = assembleReport({
  run: { id: '12345678-abcd-4000-8000-123456789abc', status: 'failed', calls_used: 100, calls_budget: 200 },
  conversations: [
    { id: 'one', language: 'en', status: 'passed', split: 'development' },
    { id: 'two', language: 'ar', status: 'failed', split: 'hidden' },
    { id: 'three', language: 'en', status: 'inconclusive', split: 'development' },
  ],
  findings: [{ id: 'f', check_id: null, title: 'Wrong queue', title_ar: 'طابور غير صحيح', severity: 'high', language: 'ar', split: 'hidden', family: 'routing', really_happened: 'PRIVATE DATA', really_happened_ar: null, evidence: { key: 'SECRET KEY' } }],
  messages: [{ conversation_id: 'one', seq: 1, speaker: 'agent', body: 'SECRET TRANSCRIPT', split: 'development' }],
});
async function extras(lang: 'en' | 'ar' = 'en'): Promise<PdfExtras> {
  return { lang, agentName: 'Test agent', focusPack: 'Government', runDate: '22 October 2026', fontBytes: await readFile('src/server/reports/fonts/NotoSansArabic.ttf'), testNames: { one: 'Reference rules', two: 'Routing', three: 'Case status' } };
}
async function textOf(pdf: Uint8Array) {
  const proxy = await getDocumentProxy(new Uint8Array(pdf));
  try { return (await extractText(proxy, { mergePages: true })).text; }
  finally { await proxy.loadingTask.destroy(); }
}

it('builds a valid PDF with saved scores, tests and safe client fields', async () => {
  const pdf = await buildReportPdf(body, await extras());
  expect(Buffer.from(pdf).subarray(0, 5).toString()).toBe('%PDF-');
  expect((await PDFDocument.load(pdf)).getPageCount()).toBeGreaterThan(0);
  const text = await textOf(pdf);
  for (const value of ['33 / 100', 'English: 50 / 100', 'Arabic: 0 / 100', 'Tests run: 3', 'Passed: 1', 'Failed: 1', 'Inconclusive: 1', 'Reference rules', 'Routing', 'Case status', 'High: Wrong queue', 'No changes applied in this run', 'Synthetic test conversations. Generated by Nazir.']) expect(text).toContain(value);
  for (const secret of ['PRIVATE DATA', 'SECRET KEY', 'SECRET TRANSCRIPT', 'calls_used', 'calls_budget']) expect(text).not.toContain(secret);
});

it('joins Arabic letters and keeps Latin words, numbers and brackets in bidi order', () => {
  expect(shapePdfLine('ببب', 'ar')).toBe('\ufe90\ufe92\ufe91');
  expect(shapePdfLine('لا', 'ar')).toBe('\ufefb');
  const mixed = shapePdfLine('النتيجة (PDF 123) من 100', 'ar');
  expect(mixed).toContain('(PDF 123)');
  expect(mixed).toContain('100');
  expect(mixed).not.toContain('321');
  expect(shapePdfLine('33 / 100', 'ar')).toBe('33 / 100');
  expect(cleanPdfText('a-b–c—d')).toBe('a b c d');
});

it('wraps long words and lines without losing text', () => {
  const lines = wrapPdfText('one two abcdefghijklmnop', 6, (v) => v.length);
  expect(lines.every((line) => line.length <= 6)).toBe(true);
  expect(lines.join('').replaceAll(' ', '')).toBe('onetwoabcdefghijklmnop');
});

it('builds Arabic and paginates long content with a footer on every page', async () => {
  const options = await extras('ar');
  options.agentName = 'وكيل خدمة العملاء';
  options.appliedFixes = Array.from({ length: 70 }, () => 'تم تحسين توجيه الطلب إلى الطابور الصحيح وتحسين الرد على العميل');
  const pdf = await buildReportPdf(body, options);
  expect((await PDFDocument.load(pdf)).getPageCount()).toBeGreaterThan(1);
  const proxy = await getDocumentProxy(new Uint8Array(pdf));
  try {
    const { text } = await extractText(proxy, { mergePages: false });
    for (const page of text) expect(page.normalize('NFKC')).toContain('ناظر');
  } finally { await proxy.loadingTask.destroy(); }
});

it('handles zero conversations honestly in both languages', async () => {
  const empty = assembleReport({ run: body.run, conversations: [], findings: [], messages: [] });
  for (const lang of ['en', 'ar'] as const) {
    const options = await extras(lang);
    const sections = clientReportSections(empty, options);
    expect(sections[0]?.lines).toEqual(['0 / 100']);
    expect(sections[1]?.lines.every((line) => line.includes('0 / 100'))).toBe(true);
    expect((await PDFDocument.load(await buildReportPdf(empty, options))).getPageCount()).toBe(1);
  }
});

it('reports only applied changes and verified fixed findings, with explicit before scores', async () => {
  const options = await extras();
  options.appliedFixes = ['Correct routing'];
  options.before = { runId: 'before123', counts: { ...body.counts, passed: 0 } };
  let sections = clientReportSections(body, options);
  expect(sections[3]?.lines.join(' ')).toContain('Before: 0 / 100');
  expect(sections[3]?.lines.join(' ')).toContain('After: 33 / 100');
  expect(sections[4]?.lines).toEqual(['High: Wrong queue']);
  options.fixedFindingIds = ['f'];
  sections = clientReportSections(body, options);
  expect(sections[4]?.lines).toEqual(['No open issues recorded']);
});
